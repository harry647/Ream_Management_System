def get_term_from_date(date_str):
    """Determine term based on date (Jan-Apr: Term 1, May-Aug: Term 2, Sep-Dec: Term 3)."""
    try:
        date_obj = datetime.strptime(date_str, '%Y-%m-%d')
        month = date_obj.month
        if 1 <= month <= 4:
            return 'Term 1'
        elif 5 <= month <= 8:
            return 'Term 2'
        elif 9 <= month <= 12:
            return 'Term 3'
        else:
            raise ValueError(f"Invalid month {month} from date {date_str}")
    except ValueError as e:
        logger.error(f"Invalid date format for {date_str}: {e}")
        raise

def import_reams_brought_data(data_list):
    """
    Import reams_brought data, deleting existing data first and allowing multiple identical entries.
    data_list: List of tuples like [('4337', 1, '2025-08-26'), ...]
    """
    # Validate input data
    if not isinstance(data_list, list):
        logger.error(f"Expected data_list to be a list, got {type(data_list)}: {data_list}")
        raise ValueError(f"Invalid data_list type: {type(data_list)}. Expected a list of tuples.")
    
    for item in data_list:
        if not isinstance(item, tuple) or len(item) != 3:
            logger.error(f"Invalid data item: {item}. Expected a tuple with 3 elements (admission_no, quantity, date_brought).")
            raise ValueError(f"Invalid data item: {item}. Expected a tuple with 3 elements.")

    conn = get_db_connection()
    cursor = conn.cursor()
    missing_students = []

    try:
        # Clear existing reams_brought data
        cursor.execute("DELETE FROM reams_brought")
        logger.info("Cleared existing reams_brought data.")

        # Group data by admission_no to calculate total quantities
        quantities_by_adm_no = {}
        for adm_no, quantity, _ in data_list:
            if adm_no not in quantities_by_adm_no:
                quantities_by_adm_no[adm_no] = 0
            quantities_by_adm_no[adm_no] += quantity

        # Adjust total_required for each student
        for adm_no, total_new_quantity in quantities_by_adm_no.items():
            cursor.execute("""
                SELECT student_id, total_required, total_brought FROM students WHERE admission_no = ?
            """, (adm_no,))
            student = cursor.fetchone()
            if not student:
                logger.warning(f"Skipping admission_no {adm_no}: No matching student found.")
                missing_students.extend([(adm_no, q, d) for a, q, d in data_list if a == adm_no])
                continue
            
            student_id, total_required, total_brought = student['student_id'], student['total_required'], student['total_brought']
            
            # Update total_required if necessary
            if total_brought + total_new_quantity > total_required:
                new_total_required = total_brought + total_new_quantity
                cursor.execute("""
                    UPDATE students SET total_required = ? WHERE student_id = ?
                """, (new_total_required, student_id))
                logger.info(f"Updated total_required for admission_no {adm_no} to {new_total_required} to accommodate {total_new_quantity} new reams.")

        # Insert reams_brought records
        for adm_no, quantity, date_brought in data_list:
            # Validate data types
            if not isinstance(adm_no, str) or not isinstance(quantity, int) or not isinstance(date_brought, str):
                logger.warning(f"Skipping invalid data for admission_no {adm_no}: Expected (str, int, str), got {type(adm_no)}, {type(quantity)}, {type(date_brought)}")
                continue

            # Find the matching student_id and form
            cursor.execute("""
                SELECT student_id, form FROM students WHERE admission_no = ?
            """, (adm_no,))
            student = cursor.fetchone()
            if not student:
                # Already logged above, skip
                continue
            
            student_id, form = student['student_id'], student['form']
            
            # Determine term based on date_brought
            term = get_term_from_date(date_brought)
            
            # Insert into reams_brought (no duplicate check)
            cursor.execute("""
                INSERT INTO reams_brought (student_id, quantity, term, form, date_brought, recorded_by)
                VALUES (?, ?, ?, ?, ?, ?)
            """, (student_id, quantity, term, form, date_brought + ' 00:00:00', 'imported'))
            
            logger.info(f"Imported reams_brought for admission_no {adm_no}: quantity {quantity}, date {date_brought}, term {term}")
        
        conn.commit()
        logger.info("Data import completed successfully.")
        
        # Verify import
        cursor.execute("SELECT COUNT(*) AS count FROM reams_brought")
        count = cursor.fetchone()['count']
        logger.info(f"Verification: {count} records found in reams_brought table.")

        # Save missing students to file
        if missing_students:
            missing_file = 'logs/missing_students.txt'
            with open(missing_file, 'w') as f:  # Overwrite file for each import
                for adm_no, quantity, date_brought in missing_students:
                    f.write(f"Admission No: {adm_no}, Quantity: {quantity}, Date: {date_brought}\n")
            logger.info(f"Saved {len(missing_students)} missing student records to {missing_file}")

    except sqlite3.Error as e:
        conn.rollback()
        logger.error(f"Import failed due to database error: {e}")
        raise
    except ValueError as e:
        conn.rollback()
        logger.error(f"Import failed due to date error: {e}")
        raise
    finally:
        release_db_connection(conn)

